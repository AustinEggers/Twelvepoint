# Breadcrumb for interior pages. $1 = page url path, $2 = page label.
crumbs() {
  cat <<JSON
  {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    "itemListElement": [
      { "@type": "ListItem", "position": 1, "name": "Home", "item": "${SITE_URL}/" },
      { "@type": "ListItem", "position": 2, "name": "$2", "item": "${SITE_URL}/$1" }
    ]
  }
JSON
}

# Three-level trail, for pages that render one on screen. The agent pages
# show "Team / Name", and breadcrumb markup has to match what a visitor sees.
crumbs3() {
  cat <<JSON
  {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    "itemListElement": [
      { "@type": "ListItem", "position": 1, "name": "Home", "item": "${SITE_URL}/" },
      { "@type": "ListItem", "position": 2, "name": "Team", "item": "${SITE_URL}/team.html" },
      { "@type": "ListItem", "position": 3, "name": "$2", "item": "${SITE_URL}/$1" }
    ]
  }
JSON
}

