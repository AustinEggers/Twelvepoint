changed=0
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

emit_block() {
  local file="$1" path="$2" img="$3" index="$4"
  local canon="${SITE_URL}${path}"
  echo "$START"
  echo "<link rel=\"canonical\" href=\"${canon}\">"
  if [ "$index" = "no" ]; then
    echo "<meta name=\"robots\" content=\"noindex, nofollow\">"
  else
    echo "<meta name=\"robots\" content=\"index, follow, max-image-preview:large, max-snippet:-1\">"
  fi
  echo "<meta property=\"og:url\" content=\"${canon}\">"
  echo "<meta property=\"og:site_name\" content=\"${BRAND}\">"
  echo "<meta property=\"og:locale\" content=\"en_US\">"
  echo "<meta property=\"og:image\" content=\"${SITE_URL}/${img}\">"
  echo "<meta property=\"og:image:alt\" content=\"${BRAND}\">"
  echo "<meta name=\"twitter:card\" content=\"summary_large_image\">"
  echo "<meta name=\"twitter:image\" content=\"${SITE_URL}/${img}\">"
  if [ "$index" = "yes" ]; then
    local ld; ld="$(page_jsonld "$file" || true)"
    if [ -n "$ld" ]; then
      echo "<script type=\"application/ld+json\">"
      # Wrap multiple top-level nodes in @graph-free array form.
      if [ "$(printf '%s' "$ld" | grep -c '"@context"')" -gt 1 ]; then
        echo "["
        printf '%s\n' "$ld"
        echo "]"
      else
        printf '%s\n' "$ld"
      fi
      echo "</script>"
    fi
  fi
  echo "$END"
}

for row in $PAGES; do
  [ -z "$row" ] && continue
  file="${row%%|*}";  rest="${row#*|}"
  path="${rest%%|*}"; rest="${rest#*|}"
  img="${rest%%|*}"
  index="${rest##*|}"
  [ -f "$file" ] || { echo "skip (missing): $file"; continue; }

  work="$tmp/$file"
  # 1. drop any previously generated block
  awk -v s="SEO:START" -v e="SEO:END" '
    index($0,s){skip=1} !skip{print} index($0,e){skip=0}
  ' "$file" > "$work"
  # 2. drop tags the generated block now owns, wherever they were before
  sed -i -E '/<meta property="og:image" content="assets\//d;
             /<meta property="og:image" content="https?:\/\//d;
             /<meta name="twitter:card"/d;
             /<meta name="twitter:image"/d;
             /<meta name="robots"/d;
             /<link rel="canonical"/d' "$work"
  # 3. splice the fresh block in ahead of </head>
  emit_block "$file" "$path" "$img" "$index" > "$tmp/block"
  awk -v bf="$tmp/block" '
    /<\/head>/ && !done { while ((getline l < bf) > 0) print l; close(bf); done=1 }
    { print }
  ' "$work" > "$tmp/out"

  if cmp -s "$tmp/out" "$file"; then
    :
  else
    changed=1
    if [ "$CHECK" = "1" ]; then
      echo "OUT OF DATE: $file"
    else
      cp "$tmp/out" "$file"
      echo "seo: $file"
    fi
  fi
done

# --------------------------------------------------------------- sitemap
# Only indexable pages. lastmod comes from the file's own mtime, so it
# stays honest without anyone maintaining a date by hand.
build_sitemap() {
  {
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
    for row in $PAGES; do
      [ -z "$row" ] && continue
      file="${row%%|*}";  rest="${row#*|}"
      path="${rest%%|*}"
      index="${rest##*|}"
      [ "$index" = "yes" ] || continue
      [ -f "$file" ] || continue
      lastmod="$(date -u -r "$file" +%Y-%m-%d)"
      case "$path" in
        /)  prio="1.0" ;;
        /listings.html|/home-value.html|/buyers.html) prio="0.9" ;;
        *)  prio="0.7" ;;
      esac
      printf '  <url>\n    <loc>%s%s</loc>\n    <lastmod>%s</lastmod>\n    <priority>%s</priority>\n  </url>\n' \
        "$SITE_URL" "$path" "$lastmod" "$prio"
    done
    # Notes carry their own SEO block from tools/build-notes.sh; they are
    # listed here purely so search engines can discover them.
    for n in notes/*.html; do
      [ -e "$n" ] || continue
      lastmod="$(date -u -r "$n" +%Y-%m-%d)"
      printf '  <url>\n    <loc>%s/%s</loc>\n    <lastmod>%s</lastmod>\n    <priority>0.6</priority>\n  </url>\n' \
        "$SITE_URL" "$n" "$lastmod"
    done
    echo '</urlset>'
  }
}

build_robots() {
  cat <<TXT
User-agent: *
Allow: /

# Not useful in search results, and the templates would read as
# duplicate/thin content against the real pages they seed.
Disallow: /login.html
Disallow: /blog-post-template.html
Disallow: /listing-template.html

Sitemap: ${SITE_URL}/sitemap.xml
TXT
}

for pair in "sitemap.xml:build_sitemap" "robots.txt:build_robots"; do
  out="${pair%%:*}"; fn="${pair##*:}"
  "$fn" > "$tmp/gen"
  if cmp -s "$tmp/gen" "$out" 2>/dev/null; then
    :
  else
    changed=1
    if [ "$CHECK" = "1" ]; then echo "OUT OF DATE: $out"
    else cp "$tmp/gen" "$out"; echo "seo: $out"; fi
  fi
done

if [ "$CHECK" = "1" ]; then
  [ "$changed" = "1" ] && { echo "run: bash tools/build-seo.sh"; exit 1; }
  echo "SEO artifacts up to date."
fi
exit 0
