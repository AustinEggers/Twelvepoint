#!/usr/bin/env bash
# =====================================================================
# build-seo.sh — stamps the domain-dependent SEO block into every page,
# then regenerates sitemap.xml and robots.txt.
#
#   bash tools/build-seo.sh            rewrite every page
#   bash tools/build-seo.sh --check    exit 1 if anything is out of date
#
# Everything that depends on the live domain lives in the generated
# region between the SEO:START / SEO:END markers, so changing SITE_URL
# below and re-running is the whole migration. Do not hand-edit inside
# the markers — this script overwrites it.
# =====================================================================
set -euo pipefail
cd "$(dirname "$0")/.."

